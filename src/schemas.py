"""Strict Pydantic v2 schemas for the Autonomous Procurement Data Swarm."""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


class VolumePriceTier(BaseModel):
    """Single quantity-break pricing tier from a supplier quote."""

    min_qty: int
    max_qty: int | None = None
    unit_price: float


class AmbiguityFlag(BaseModel):
    """Audit flag recording missing, ambiguous, or anomalous quote fields."""

    field_name: str
    raw_value: str | None = None
    reason: str
    severity: Literal["LOW", "MEDIUM", "HIGH"]


class NormalizedQuote(BaseModel):
    """Canonical master-data representation of a supplier quotation."""

    quote_id: str
    source_file: str
    supplier_id: str
    supplier_name: str
    supplier_email: str | None = None
    source_language: Literal["en", "fr"]
    rfq_reference: str
    part_number: str
    part_description: str
    currency: str
    incoterm: Literal["EXW", "FOB", "DDP"] | None = None
    incoterm_location: str | None = None
    lead_time_value: float | None = None
    lead_time_max_value: float | None = None
    lead_time_unit: Literal["business_days", "calendar_days", "weeks"] | None = None
    price_tiers: list[VolumePriceTier] = Field(default_factory=list)
    tooling_fee: float | None = None
    shipping_fee: float | None = None
    payment_terms: str | None = None
    certifications: list[str] = Field(default_factory=list)
    quote_valid_until: str | None = None
    ambiguity_flags: list[AmbiguityFlag] = Field(default_factory=list)
    extraction_notes: list[str] = Field(default_factory=list)
    master_data_hygiene_actions: list[str] = Field(default_factory=list)


class TCOCalculationConfig(BaseModel):
    """Configuration parameters for deterministic Total Cost of Ownership (TCO) modeling."""

    target_quantity: int = 250
    target_lead_time_business_days: float = 15.0
    delay_penalty_per_day_usd: float = 350.0
    fx_rates_to_usd: dict[str, float] = Field(
        default_factory=lambda: {"USD": 1.0, "EUR": 1.085, "MXN": 0.058}
    )
    incoterm_uplift_pct: dict[str, float] = Field(
        default_factory=lambda: {
            "DDP": 0.00,
            "FOB": 0.065,
            "EXW": 0.110,
            "UNKNOWN": 0.120,
        }
    )
    incoterm_customs_buffer_pct: dict[str, float] = Field(
        default_factory=lambda: {
            "DDP": 0.00,
            "FOB": 0.025,
            "EXW": 0.040,
            "UNKNOWN": 0.050,
        }
    )


class QuoteTCOBreakdown(BaseModel):
    """Deterministic USD Total Cost of Ownership and risk breakdown for one quote."""

    quote_id: str
    supplier_id: str
    supplier_name: str
    source_language: Literal["en", "fr"]
    status: Literal["COMPLETE", "INCOMPLETE_DATA"]
    applicable_tier_range: str | None = None
    unit_price_original: float | None = None
    original_currency: str | None = None
    unit_price_usd: float | None = None
    merchandise_subtotal_usd: float | None = None
    tooling_fee_usd: float = 0.0
    shipping_and_incoterm_usd: float = 0.0
    lead_time_business_days: float | None = None
    delay_days: float = 0.0
    delay_penalty_usd: float = 0.0
    total_cost_of_ownership_usd: float | None = None
    delivery_risk_score: float = Field(default=0.0, ge=0.0, le=100.0)
    composite_score: float | None = None
    rank: int | None = None
    calculation_warnings: list[str] = Field(default_factory=list)
    audit_trail: list[str] = Field(default_factory=list)


class CounterofferDraft(BaseModel):
    """Localized negotiation counteroffer email drafted for a non-winning supplier."""

    quote_id: str
    supplier_id: str
    supplier_name: str
    supplier_email: str | None = None
    language: Literal["en", "fr"]
    subject: str
    target_unit_price_original: float | None = None
    currency: str
    target_lead_time_business_days: float | None = None
    requested_incoterm: str | None = None
    email_body: str
    negotiation_leverage_points: list[str] = Field(default_factory=list)


class ProcurementStrategyReport(BaseModel):
    """Executive recommendation report and counteroffer bundle generated by the strategist agent."""

    rfq_reference: str
    part_number: str
    target_quantity: int
    recommended_supplier_id: str
    recommended_supplier_name: str
    recommended_quote_id: str
    recommended_tco_usd: float
    executive_summary: str
    key_tradeoffs: list[str] = Field(default_factory=list)
    data_hygiene_risks: list[str] = Field(default_factory=list)
    executive_report_markdown: str
    counteroffers: list[CounterofferDraft] = Field(default_factory=list)


class PipelineMetrics(BaseModel):
    """Quantitative execution and ROI telemetry for a pipeline run."""

    rfq_reference: str
    model_used: str
    quotes_processed: int
    complete_quotes: int
    incomplete_quotes: int
    ambiguity_flags_total: int
    hygiene_actions_total: int
    counteroffers_generated: int
    recommended_supplier_id: str
    recommended_tco_usd: float
    second_best_tco_usd: float | None = None
    tco_savings_vs_next_best_usd: float | None = None
    tco_spread_usd: float | None = None
    execution_time_seconds: float
    estimated_manual_hours_saved: float


class PipelineResult(BaseModel):
    """Complete end-to-end output bundle produced by ProcurementSwarmPipeline."""

    config: TCOCalculationConfig
    normalized_quotes: list[NormalizedQuote]
    tco_breakdowns: list[QuoteTCOBreakdown]
    strategy_report: ProcurementStrategyReport
    metrics: PipelineMetrics
